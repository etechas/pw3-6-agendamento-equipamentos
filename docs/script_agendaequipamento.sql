CREATE DATABASE AgendaEquipamentos;

USE AgendaEquipamentos;

CREATE TABLE RES_ARMARIO (
    ID         BIGINT        IDENTITY(1,1) NOT NULL,
    NR_ARMARIO VARCHAR(255)  NOT NULL,
    NM_ALUNO   VARCHAR(255)  NOT NULL,
    DT_INICIO  DATETIME2(6)  NOT NULL,
    DT_FIM     DATETIME2(6)  NOT NULL,
    ATIVO      BIT           NOT NULL CONSTRAINT DF_RES_ARMARIO_ATIVO DEFAULT 1,
    CONSTRAINT PK_RES_ARMARIO PRIMARY KEY (ID),
    CONSTRAINT CK_RES_ARMARIO_PERIODO CHECK (DT_FIM > DT_INICIO)
    );

